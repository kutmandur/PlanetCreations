const EXACT_LABELS = Object.freeze({
    NoResearchRequirement: 'No research requirement',
    CoastersGroup: 'Coasters category unlock',
    FlatRidesGroup: 'Flat rides category unlock',
    TrackedRidesGroup: 'Tracked rides category unlock',
    PowerGroup: 'Power category unlock',
    WaterGroup: 'Water category unlock',
    TransportGroup: 'Transport category unlock',
    FlumesGroup: 'Flumes category unlock',
    H2Bowl: 'H2 Bowl',
});

function humanizePart(value) {
    if (EXACT_LABELS[value]) return EXACT_LABELS[value];
    return value
        .replace(/BP$/, 'Blueprint')
        .replace(/&/g, ' & ')
        .replace(/([a-z])([A-Z])/g, '$1 $2')
        .replace(/([A-Za-z])(\d+)/g, '$1 $2')
        .replace(/(\d+)([A-Za-z])/g, '$1 $2')
        .replace(/\.(?=[A-Z])/g, '. ')
        .replace(/\s+/g, ' ')
        .trim();
}

function researchCategory(id) {
    if (id === 0) return 'No requirement';
    if (id === 1000 || id === 1001) return 'Special unlock';
    if (id >= 2000 && id <= 2006) return 'Research category';
    if ((id >= 2100 && id < 2200) || (id >= 2900 && id < 3000)) return 'Flat rides & blueprints';
    if (id >= 2200 && id < 2300) return 'Tracked rides';
    if (id >= 2300 && id < 2400) return 'Power facilities';
    if (id >= 2400 && id < 2500) return 'Water facilities';
    if (id >= 2500 && id < 2600) return 'Transport rides';
    if (id >= 2600 && id < 2700) return 'Coasters & blueprints';
    if (id >= 2700 && id < 2800) return 'Flumes & blueprints';
    return 'Future or unknown content';
}

export function getPlanetCoaster2ResearchPack(value) {
    const id = Number(value);
    const rawName = Number.isSafeInteger(id) ? PLANET_COASTER_2_RESEARCH_CATALOG[id] : null;
    if (!rawName) {
        return {
            id: Number.isSafeInteger(id) ? id : value,
            label: `Unknown research reward #${value}`,
            category: 'Future or unknown content',
            known: false,
        };
    }
    return {
        id,
        label: rawName.split('_').map(humanizePart).join(' · '),
        category: researchCategory(id),
        known: true,
    };
}
